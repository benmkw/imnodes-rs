/*!
High-level, safe bindings for [imnodes](https://github.com/Nelarius/imnodes),
a node editor extension for [imgui-rs](https://github.com/imgui-rs/imgui-rs).

Based on the C API bindings generated by [cimnodes](https://github.com/cimgui/cimnodes).

# Usage

1. Create an [`imnodes::Context`](crate::Context) once at application startup.
2. Create an [`imnodes::EditorContext`](crate::EditorContext) for each node editor you want to display.
3. Use the [`imnodes::editor`](crate::editor) function to define the node editor content.
   The editor function automatically sets the context as current.

```no_run
# use imgui;
# use imnodes;
# struct State<'a> { editor_context: imnodes::EditorContext<'a> }
fn main() {
    let mut state: State = unimplemented!();
    let ui: &imgui::Ui = unimplemented!();
    // Before calling editor:
    let mut node_id_gen = state.editor_context.new_identifier_generator();

    // Apply colors using the closure-based API which handles popping automatically
    state.editor_context.push_style(
        &imnodes::StyleDesc {
            colors: &[(imnodes::ColorStyle::TitleBar, [0.8, 0.5, 0.1].into())],
            ..Default::default()
        },
        |context| {
            let outer_scope = imnodes::editor(context, |mut editor_scope| {
                editor_scope.add_node(node_id_gen.next_node(), |mut node_scope| {
                    node_scope.add_titlebar(|| ui.text("My Node"));
                    node_scope.add_input(&imnodes::InputAttributeDesc::new(node_id_gen.next_input_pin(), imnodes::PinShape::Circle), || {
                         ui.text("Input Pin");
                    });
                    node_scope.add_output(&imnodes::OutputAttributeDesc::new(node_id_gen.next_output_pin(), imnodes::PinShape::Triangle), || {
                         ui.text("Output Pin");
                    });
                });
                // Add more nodes and links...
            });

            // Handle events after the editor scope ends
            if let Some(link) = outer_scope.links_created() {
               // handle new link creation
            }
            if let Some(dropped_link_id) = outer_scope.get_destroyed_link() {
                // handle link deletion
            }
        },
    );
}
```

Identifiers

imnodes requires unique integer IDs for nodes, pins (attributes), and links.
The [IdentifierGenerator] struct provides a convenient way to generate these unique IDs within an editor context.

# Pitfalls

*   **Styling outside `editor()`**: If you push styles (colors, vars) *before* calling [`editor()`], you **must** call [`EditorContext::set_as_current_editor()`] first. However, [`EditorContext::style()`] and closure-based methods enforce this automatically.
*   **Coordinate Systems**: Be careful with [`CoordinateSystem`]. `ScreenSpace` is absolute (window), `EditorSpace` is relative to the canvas (ignoring pan), and `GridSpace` is relative to the grid content (including pan). `GridSpace` is usually what you want for saving/loading.

# See Also

*   [`ColorStyle`] for color styling.
*   [`StyleVar`] for variable styling.
*   [`AttributeFlags`] for attribute behavior.
*/

