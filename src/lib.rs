/// Provides unique identifiers for nodes, pins, attributes, and links within an editor context.
///
/// Create one generator per [EditorContext] using [EditorContext::new_identifier_generator].
#[derive(Debug)]
pub struct IdentifierGenerator {
    current_node: i32,
    // Input pins, output pins, and static attributes share the same ID space in imnodes.
    current_attribute: i32,
    current_link: i32,
}

impl IdentifierGenerator {
    /// Creates a new identifier generator, starting all IDs from 0.
    /// Intended to be called via [EditorContext::new_identifier_generator].
    pub(crate) fn new() -> Self {
        Self {
            current_node: 0,
            current_attribute: 0,
            current_link: 0,
        }
    }

    /// Creates a new identifier generator with specific starting states.
    /// Useful for restoring state after loading.
    pub fn new_from_state(current_node: i32, current_attribute: i32, current_link: i32) -> Self {
        Self {
            current_node,
            current_attribute,
            current_link,
        }
    }

    /// Generates the next unique ID for a node.
    pub fn next_node(&mut self) -> NodeId {
        let id = self.current_node;
        self.current_node = self.current_node.checked_add(1).unwrap();
        NodeId { id }
    }

    /// Generates the next unique ID for an input pin.
    pub fn next_input_pin(&mut self) -> InputPinId {
        let id = self.current_attribute;
        self.current_attribute = self.current_attribute.checked_add(1).unwrap();
        InputPinId { id }
    }

    /// Generates the next unique ID for an output pin.
    pub fn next_output_pin(&mut self) -> OutputPinId {
        let id = self.current_attribute;
        self.current_attribute = self.current_attribute.checked_add(1).unwrap();
        OutputPinId { id }
    }

    /// Generates the next unique ID for a static attribute (one without a pin).
    pub fn next_attribute(&mut self) -> AttributeId {
        let id = self.current_attribute;
        self.current_attribute = self.current_attribute.checked_add(1).unwrap();
        AttributeId { id }
    }

    /// Generates the next unique ID for a link.
    pub fn next_link(&mut self) -> LinkId {
        let id = self.current_link;
        self.current_link = self.current_link.checked_add(1).unwrap();
        LinkId { id }
    }

    /// Registers a used node ID, ensuring the generator will not produce it again.
    pub fn register_node_id(&mut self, id: &NodeId) {
        if id.id >= self.current_node {
            self.current_node = id.id + 1;
        }
    }

    /// Registers a used input pin ID, ensuring the generator will not produce it again.
    pub fn register_input_pin_id(&mut self, id: &InputPinId) {
        if id.id >= self.current_attribute {
            self.current_attribute = id.id + 1;
        }
    }

    /// Registers a used output pin ID, ensuring the generator will not produce it again.
    pub fn register_output_pin_id(&mut self, id: &OutputPinId) {
        if id.id >= self.current_attribute {
            self.current_attribute = id.id + 1;
        }
    }

    /// Registers a used attribute ID, ensuring the generator will not produce it again.
    pub fn register_attribute_id(&mut self, id: &AttributeId) {
        if id.id >= self.current_attribute {
            self.current_attribute = id.id + 1;
        }
    }

    /// Registers a used link ID, ensuring the generator will not produce it again.
    pub fn register_link_id(&mut self, id: &LinkId) {
        if id.id >= self.current_link {
            self.current_link = id.id + 1;
        }
    }
}

